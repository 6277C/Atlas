namespace atlas {
void Chassis::driveDistance(float distance, float angle, int timeout, DriveDistanceParams params, bool async) {
  this->requestMotionStart();

  if (!this->motionRunning)
    return;

  if (async) {
    pros::Task task([&]() { driveDistance(distance, angle, timeout, params, false); });
    this->endMotion();
    pros::delay(10);
    return;
  }

  double t;
  double x;
  double v;
  double a;
  double deltaAngle;
  double deltaLinear;
  MotionProfile1D profiler;
  // get inches per second from user max speed param
  float trueMaxSpeed = (params.maxSpeed / 100.00) * (M_PI * drivetrain.wheelDiameter * drivetrain.rpm / 60);
  // generate motion profile 
  MotionProfile1DResult result = profiler.compute(trueMaxSpeed, params.timeToMaxSpeed, .01, distance);
  distTraveled = 0;
  size_t profileIndex = 0;
  // reset functions
  Pose lastPose = getPose();
  linearPID.reset();
  angularPID.reset();
  linearPID.setConstants(relativeLinearParams);
  angularPID.setConstants(globalAngularParams);
  float start = vertical.getDist();
  Timer timer(timeout);

  while (!timer.isDone() && !relativeLinearExit.getExit()) {
    // update position
    Pose pose = getPose();
    // update errors
    distTraveled += pose.distance(lastPose);
    lastPose = pose;
    deltaAngle = angleError(angle, pose.angle);
    deltaLinear = distance + start - vertical.getDist();

    // sequence through the array generated by the motion profiler
    if (profileIndex < result.t.size()) {
      x = result.x[profileIndex];
      v = result.v[profileIndex];
      a = result.a[profileIndex];
      ++profileIndex;
    }

    // update exit conditions
    relativeLinearExit.compute(deltaLinear);

    //use motion profile combined with linear PID for error correction
    double linearCMD = v + linearPID.compute(x - distTraveled);
    //use anuglarPID to adjust for small heading errors
    double headingCMD = angularPID.compute(deltaAngle);

    double leftCMD = linearCMD - headingCMD;
    double rightCMD = linearCMD + headingCMD;

    // convert inches per second to rpm with clamping in function
    left_motors.move_velocity(linearToRPM(leftCMD, drivetrain.wheelDiameter, drivetrain.rpm / 600));
    right_motors.move_velocity(linearToRPM(rightCMD, drivetrain.wheelDiameter, drivetrain.rpm / 600));
    pros::delay(10);
  }
  drivetrain.leftMotors->move(0);
  drivetrain.rightMotors->move(0);
  // indicate function is finished
  distTraveled = -1;
  this->endMotion();
}
} // namespace atlas